// node tests/local_business.mjs — no packages or live Discord credentials needed.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const rules=readFileSync(new URL('../static/rules.js',import.meta.url),'utf8');
const source=readFileSync(new URL('../static/local-business.js',import.meta.url),'utf8');
function environment(storage=new Map()){
 const context=vm.createContext({console,Intl,Date,structuredClone,window:{heritageNavigate:async()=>{}},localStorage:{getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v)}});
 vm.runInContext(`let state={sales:[],machines:[],tombolaRecords:[],events:[],salesWeek:{archives:[],lastResetDate:null},catalog:{voitures:[],motos:[]}};let tombolaWeek='',salesScope='',search='',sequence=0;const localId=()=>String(++sequence);const toast=()=>{};`+rules+'\n'+source+'\nwindow.action=window.heritageLocalBusiness();',context);
 return {context,action:(...args)=>context.window.action(...args),snapshot:()=>JSON.parse(vm.runInContext('JSON.stringify(state)',context)),storage};
}
const env=environment();
await assert.rejects(env.action('raffle-record',null,{vehicle0:'Brioso'}),/deux véhicules/);
assert.equal(env.snapshot().tombolaRecords.length,0);
const values={vehicle0:'Brioso',type0:'voiture',price0:'125 000',vehicle1:'Bati 801',type1:'moto',price1:''};
await env.action('raffle-record',null,values);
const id=env.snapshot().tombolaRecords[0].id;
assert.equal(env.snapshot().tombolaRecords[0].vehicles[0].price,125000);
assert.equal(env.snapshot().tombolaRecords[0].vehicles[1].price,null);
await env.action('vehicle-buy',id+'|0');await env.action('vehicle-pay',id+'|0');
await env.action('raffle-record',id,{...values,price0:'140000'});
assert.equal(env.snapshot().tombolaRecords[0].vehicles[0].paid,true);
assert.equal(env.snapshot().tombolaRecords[0].vehicles[0].bought,true);
assert.equal(env.snapshot().tombolaRecords[0].vehicles[0].price,140000);
const before=env.snapshot();
await assert.rejects(env.action('raffle-record',id,{...values,price0:'-10'}));
assert.deepEqual(env.snapshot(),before,'Invalid input must not change saved data');
await env.action('pay-all',id);
assert.ok(env.snapshot().tombolaRecords[0].vehicles.every(v=>v.paid));
const restored=environment(env.storage);
assert.deepEqual(restored.snapshot().tombolaRecords,env.snapshot().tombolaRecords,'A reload must restore vehicles');
await restored.action('reset-payments',id);
assert.ok(restored.snapshot().tombolaRecords[0].vehicles.every(v=>!v.paid&&!v.bought));
const employee=vm.runInContext('Object.keys(BOT_RULES.employees)[0]',env.context);
await env.action('add-sale',null,{group:'Groupe test',giver:'12345',employee,amount:''});
assert.equal(env.snapshot().sales[0].amount,5000000);
assert.equal(env.snapshot().summary.group,4000000);
assert.equal(env.snapshot().summary.company,750000);
assert.equal(env.snapshot().summary.loss,250000);
assert.equal(env.snapshot().days.reduce((n,d)=>n+d.amount,0),5000000);
await env.action('add-machine',null,{launcher:employee,amount:''});
assert.equal(env.snapshot().machines[0].amount,1000000);
assert.equal(env.snapshot().employeesTotal[0].count,1);
await assert.rejects(env.action('add-machine',null,{launcher:employee}),/lot en cours/);
await assert.rejects(env.action('recover',env.snapshot().machines[0].id),/4 h 45/);
await env.action('cancel-machine',env.snapshot().machines[0].id);
assert.equal(env.snapshot().machines[0].cancelled,true);
const savedBefore=env.snapshot();env.context.localStorage.setItem=()=>{throw Error('Quota');};
await assert.rejects(env.action('vehicle-pay',id+'|0'),/Sauvegarde impossible/);
assert.deepEqual(env.snapshot(),savedBefore,'Storage failures must not announce or apply a successful save');
const corrupted=new Map([['heritage.local-business.v1','invalid-json']]),broken=environment(corrupted);
await assert.rejects(broken.action('raffle-record',null,values),/illisibles ou inaccessibles/);
assert.equal(corrupted.get('heritage.local-business.v1'),'invalid-json','Unreadable data must be preserved');
console.log('OK: vehicles, edits, prices, purchase/payment, reload, sales, machines, validation and storage failures.');
